import { mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { parseArgs } from "node:util";
import { OpenChasquiError, parseDocument, run } from "@abitech/openchasqui-core";
import { postmanEmitter } from "@abitech/openchasqui-emitter-postman";
import { openApiLoader } from "@abitech/openchasqui-loader-openapi";
import type { OpenChasquiConfig, Plugin } from "@abitech/openchasqui-spec";

/** Marks a folder as generated, so the next run may replace it. */
export const MARKER = ".openchasqui";

const DEFAULT_CONFIG = "openchasqui.config.yaml";
const BUILT_IN_PLUGINS: readonly Plugin[] = [openApiLoader, postmanEmitter];

const HELP = `Usage: openchasqui <command> [options]

Commands:
  generate   Emit the collections for every target in the configuration

Options:
  -c, --config <file>   Configuration file (default: ${DEFAULT_CONFIG})
  -h, --help            Show this help
  -v, --version         Show the version
`;

export interface Console {
  log(message: string): void;
  error(message: string): void;
}

/** Runs the command line and returns the process exit code. */
export async function main(argv: readonly string[], output: Console = console): Promise<number> {
  const { values, positionals } = parseArgs({
    args: [...argv],
    allowPositionals: true,
    options: {
      config: { type: "string", short: "c", default: DEFAULT_CONFIG },
      help: { type: "boolean", short: "h", default: false },
      version: { type: "boolean", short: "v", default: false },
    },
  });

  if (values.version) {
    output.log(await version());
    return 0;
  }
  const [command] = positionals;
  if (values.help || !command) {
    output.log(HELP);
    return values.help ? 0 : 1;
  }
  if (command !== "generate") {
    output.error(`Unknown command "${command}".\n\n${HELP}`);
    return 1;
  }

  try {
    return await generate(resolve(values.config), output);
  } catch (error) {
    if (error instanceof OpenChasquiError) {
      output.error(`error ${error.code}: ${error.message}`);
      return 1;
    }
    throw error;
  }
}

async function generate(configPath: string, output: Console): Promise<number> {
  const base = dirname(configPath);
  const config = parseDocument(await readFile(configPath, "utf8")) as OpenChasquiConfig;
  const reader = { readText: (path: string) => readFile(resolve(base, path), "utf8") };
  const result = await run(config, { reader, plugins: BUILT_IN_PLUGINS });

  for (const finding of result.findings) {
    const where = finding.operationId ? ` (${finding.operationId})` : "";
    output.error(`${finding.severity} ${finding.rule}: ${finding.message}${where}`);
  }

  const outputRoot = resolve(base, config.output);
  for (const { target, files } of result.outputs) {
    const folder = join(outputRoot, target);
    await replaceFolder(folder);
    for (const file of files) {
      const path = join(folder, ...file.path.split("/"));
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, file.contents, "utf8");
    }
    output.log(`${target}: ${files.length} files in ${relative(process.cwd(), folder) || "."}`);
  }
  return result.findings.some((finding) => finding.severity === "error") ? 1 : 0;
}

/** Empties a folder only if an earlier run created it. */
async function replaceFolder(folder: string): Promise<void> {
  const exists = await stat(folder).then(
    (info) => info.isDirectory(),
    () => false,
  );
  if (exists && (await readdir(folder)).length > 0) {
    const marked = await stat(join(folder, MARKER)).then(
      () => true,
      () => false,
    );
    if (!marked) {
      throw new OpenChasquiError(
        "unsafe-output-path",
        `${folder}${sep} has files that openchasqui did not create; choose another output.`,
      );
    }
    await rm(folder, { recursive: true });
  }
  await mkdir(folder, { recursive: true });
  await writeFile(join(folder, MARKER), "Generated by openchasqui. Do not edit by hand.\n", "utf8");
}

async function version(): Promise<string> {
  const manifest = new URL("../package.json", import.meta.url);
  return (JSON.parse(await readFile(manifest, "utf8")) as { version: string }).version;
}
